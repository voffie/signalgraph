import { Effect, FileSystem, Path } from "effect";

import type { Config } from "../config/index.ts";
import * as Naming from "../internal/naming.ts";
import type { SchemaData } from "./loadSchema.ts";

const indent = (text: string, spaces = 2) =>
  text
    .split("\n")
    .map((line) => " ".repeat(spaces) + line)
    .join("\n");

function generateMessageEntries(messages: SchemaData["messages"]) {
  return [...messages.keys()].map(
    (name, i) => `${JSON.stringify(Naming.toPropertyName(name))}: message(${JSON.stringify(name)}, message${i})`
  );
}

function generateConsumerEntries(consumers: SchemaData["consumers"]) {
  return [...consumers.keys()].map(
    (name, i) => `${JSON.stringify(Naming.toPropertyName(name))}: consumer(consumer${i})`
  );
}

function generateTypeAliases(messageExportNames: SchemaData["messageExportNames"]) {
  return [...messageExportNames.keys()].map(
    (name, i) => `export type ${Naming.toTypeName(name)}Payload = typeof message${i}.schema.Type;`
  );
}

function generateMessageGraph(data: SchemaData) {
  return [...data.messages.values()].map((message, messageIndex) => {
    const consumerNames = [...data.consumers.values()]
      .flatMap((consumer, i) => (consumer.message === message ? [`consumer${i}`] : []))
      .join(", ");

    return `[${JSON.stringify(message.name)}]: {
  definition: message${messageIndex},
  consumers: [${consumerNames}]
}`;
  });
}

/** Writes client code that derives payload types directly from the imported schemas. */
export const generateClient = Effect.fn(function* (config: Config, data: SchemaData) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;

  const outputPath = config.out + "/index.ts";
  const outputDir = path.dirname(outputPath);
  yield* fs.makeDirectory(outputDir, { recursive: true });

  const header = `// This file was generated by SignalGraph
// Do not edit this file directly`;

  const entries = [...generateMessageEntries(data.messages), ...generateConsumerEntries(data.consumers)];

  let schemaRelativePath = path.relative(outputDir, config.schema);

  if (!schemaRelativePath.startsWith(".")) {
    schemaRelativePath = "./" + schemaRelativePath;
  }

  const schemaExportNames = [
    ...[...data.messageExportNames.values()].map((binding, i) => `${binding} as message${i}`),
    ...[...data.consumerExportNames.values()].map((binding, i) => `${binding} as consumer${i}`)
  ];

  const schemaImport =
    schemaExportNames.length > 0
      ? `import {\n${indent(schemaExportNames.join(",\n"))}\n} from ${JSON.stringify(schemaRelativePath)};`
      : "";

  const imports = [
    'import type { Effect } from "effect";',
    'import * as Runtime from "signalgraph/runtime";',
    schemaImport
  ]
    .filter(Boolean)
    .join("\n");

  const aliases = generateTypeAliases(data.messageExportNames).join("\n\n");

  const messageGraph = [
    "/** Message and consumer declarations for the client and deployment tools. */",
    "export const messageGraph: Runtime.MessageGraph = {",
    indent(generateMessageGraph(data).join(",\n")),
    "};"
  ].join("\n");

  const bindings = [
    ...(data.messages.size === 0 ? [] : ["message"]),
    ...(data.consumers.size === 0 ? [] : ["consumer"])
  ];

  const resourceParameter = bindings.length === 0 ? "" : `{ ${bindings.join(", ")} }`;

  const exportClient = [
    "/** Builds a client using the configured SignalGraph broker. */",
    `export const Client = Runtime.createClient(messageGraph, (${resourceParameter}) => ({`,
    indent(entries.join(",\n")),
    "}));",
    "",
    "/** Client with payload types inferred from the schema declarations. */",
    "export type Client = Effect.Success<typeof Client>;"
  ].join("\n");

  const source = [header, imports, aliases, messageGraph, exportClient].join("\n\n");

  yield* fs.writeFileString(outputPath, source, { flag: "w" });
});
