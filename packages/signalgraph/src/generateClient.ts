import { Effect, FileSystem, Path, SchemaRepresentation } from "effect";
import type { SchemaData } from "./loadSchema.ts";
import type { Config } from "./config.ts";
import type { MessageSchema } from "./message.ts";

const toCamelCase = (text: string) =>
  text
    .split(".")
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");

const toPascalCase = (text: string) =>
  text.split(".")
    .map((part) => part[0].toUpperCase() + part.slice(1))
    .join("");

const indent = (text: string, spaces = 2) =>
  text
    .split("\n")
    .map((line) => " ".repeat(spaces) + line)
    .join("\n");

function generateSchemaType(schema: MessageSchema) {
  const document = SchemaRepresentation.fromAST(schema.ast);
  const multi = SchemaRepresentation.toMultiDocument(document);
  const code = SchemaRepresentation.toCodeDocument(multi);

  return code.codes[0].Type;
};

function generateMessageEntries(messages: SchemaData["messages"]) {
  return messages.map((message) => `${toCamelCase(message.name)}: Message<${toPascalCase(message.name)}Payload>;`.trim());
}

function generateConsumerEntries(consumers: SchemaData["consumers"]) {
  return consumers.map((consumer) => `${toCamelCase(consumer.name)}: Consumer<${toPascalCase(consumer.message.name)}Payload>;`.trim());
}

function generateTypeAliases(messages: SchemaData["messages"]) {
  return messages.map(
    (message) =>
      `export type ${toPascalCase(message.name)}Payload = ${generateSchemaType(message.schema)}`
  );
}

function generateRouting(data: SchemaData) {
  return data.messages.map((message) =>
    `${toCamelCase(message.name)}: [${data.consumers
      .map((consumer) => (consumer.message.name === message.name ? '"' + consumer.name + '"' : ""))
      .filter(Boolean)
      .sort((a, b) => a.localeCompare(b))
      .join(", ")
    }],`);
}

export const generateClient = Effect.fn(function* (config: Config, data: SchemaData) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;

  const outputPath = config.out + "/index.ts";
  const outputDir = path.dirname(outputPath);

  yield* fs.makeDirectory(outputDir, { recursive: true });

  const header = `// This file was generated by SignalGraph
// Do not edit this file directly`;

  const entries = [
    ...generateMessageEntries(data.messages),
    ...generateConsumerEntries(data.consumers)
  ];

  const imports =
    'import { Effect } from "effect";' +
    '\nimport { Consumer, Message, Routing, createClient } from "@signalgraph/runtime";' +
    `\nimport { ${config.broker.layer} } from "${config.broker.package}";`;

  const aliases = generateTypeAliases(data.messages).join("\n\n");

  const client =
    [
      "export type Client = {",
      indent(entries.join("\n")),
      "};"
    ].join("\n");

  const routing =
    [
      "const routing = {",
      indent(generateRouting(data).join(",\n")),
      "} satisfies Routing;"
    ].join("\n");

  const exportClient = `export const client = createClient<Client>(routing).pipe(Effect.provide(${config.broker.layer}));`;

  const source = [
    header,
    imports,
    aliases,
    client,
    routing,
    exportClient
  ].join("\n\n");

  yield* fs.writeFileString(outputPath, source, { flag: "w" });
})
